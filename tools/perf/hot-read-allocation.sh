#!/usr/bin/env bash
#
# Phase 0 of docs/design/load-protection.md: what do members allocate when many clients read the
# same large value? Runs HotReadAllocation once per scenario, each in its own JVM with fixed 64 KB
# TLABs so that Flight Recorder records every allocation above 64 KB, and writes one Markdown
# report and one .jfr recording per scenario to the output directory (default target/fanout).
#
#   ./mvnw -B -ntp -DskipTests -pl hecaton -am install   # Hecaton into the local repository
#   mvn -f benchmarks/pom.xml package
#   tools/perf/hot-read-allocation.sh [output-dir] [extra HotReadAllocation options...]
#
# e.g. tools/perf/hot-read-allocation.sh target/fanout --value-size 4m --gets 1000
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
out=${1:-target/fanout}
shift || true
jar=benchmarks/target/benchmarks.jar
[[ -f $jar ]] || { echo "build $jar first (see the top of this script)" >&2; exit 2; }
mkdir -p "$out"

# a self-signed certificate for 127.0.0.1, used as key store and trust store by members and clients
keystore=$out/fanout.p12
if [[ ! -f $keystore ]]; then
    keytool -genkeypair -alias fanout -keyalg EC -groupname secp256r1 -validity 7 \
        -dname CN=localhost -ext SAN=ip:127.0.0.1,dns:localhost \
        -storetype PKCS12 -keystore "$keystore" -storepass changeit -keypass changeit >/dev/null
fi

jvm=(-Xms6g -Xmx6g -Dstdout.encoding=UTF-8 -XX:TLABSize=64k -XX:-ResizeTLAB -XX:FlightRecorderOptions:stackdepth=96
     --enable-native-access=ALL-UNNAMED --add-modules java.se
     --add-exports java.base/jdk.internal.ref=ALL-UNNAMED
     --add-opens java.base/java.lang=ALL-UNNAMED --add-opens java.base/sun.nio.ch=ALL-UNNAMED
     --add-opens java.management/sun.management=ALL-UNNAMED
     --add-opens jdk.management/com.sun.management.internal=ALL-UNNAMED)

# product caller format routing tls [options]: caller "member" reads through the map proxies of the
# members, "short-lived-client" opens a new client for every read
scenarios=(
    "hazelcast client BINARY ALL_MEMBERS no"
    "hazelcast client BINARY SINGLE_MEMBER no"
    "hazelcast client OBJECT ALL_MEMBERS no"
    "hazelcast member BINARY - no"
    "hazelcast member BINARY - no --sync"
    "hazelcast member BINARY - no --sync --near-cache BINARY"
    "hazelcast member BINARY - no --sync --near-cache OBJECT"
    "hazelcast member BINARY - no --sync --near-cache OBJECT --warm-up-gets 0 --gets 256"
    "hazelcast short-lived-client BINARY ALL_MEMBERS no --gets 300 --warm-up-gets 20"
    "hecaton client BINARY ALL_MEMBERS no"
    "hecaton client BINARY ALL_MEMBERS yes"
    "hecaton client BINARY SINGLE_MEMBER yes"
    "hecaton client OBJECT ALL_MEMBERS no"
    "hecaton member BINARY - yes"
    "hecaton member BINARY - yes --sync"
    "hecaton short-lived-client BINARY ALL_MEMBERS yes --gets 300 --warm-up-gets 20"
)

summary=$out/summary.md
{
    echo "# Hot read allocation"
    echo
    echo "Generated by \`tools/perf/hot-read-allocation.sh\` on $(date -u +%Y-%m-%d), $(java -version 2>&1 | grep -v "^Picked up" | head -1)."
    echo
} > "$summary"
status=0
for scenario in "${scenarios[@]}"; do
    read -r product caller format routing tls options <<< "$scenario"
    args=(--product "$product" --caller "$caller" --format "$format" --out "$out")
    [[ $routing != - ]] && args+=(--routing "$routing")
    [[ $tls == yes ]] && args+=(--key-store "$keystore")
    [[ -n ${options:-} ]] && read -ra extra <<< "$options" && args+=("${extra[@]}")
    echo "== $scenario" >&2
    if java "${jvm[@]}" -cp "$jar" uk.org.hecaton.benchmarks.fanout.HotReadAllocation "${args[@]}" "$@" \
            > "$out/last-run.log" 2>&1; then
        sed -n '/^## /,$p' "$out/last-run.log" >> "$summary"
    else
        status=1
        { echo "## $scenario"; echo; echo "Failed, see the log:"; echo; echo '```'; tail -40 "$out/last-run.log"; echo '```'; echo; } >> "$summary"
    fi
done
echo "report: $summary" >&2
exit $status
