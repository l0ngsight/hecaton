#!/usr/bin/env bash
#
# Generates the branch rebrand/<tag> from the upstream snapshot of <tag> on
# upstream/main: one commit, child of that snapshot, holding the output of
# tools/rebrand/Rebrand.java. The branch is generated only; never edit it by hand.
#
# Usage: tools/rebrand/rebrand.sh <tag>        e.g. v5.7.0
#
# Requires JDK 25 (`java` on PATH or JAVA_HOME). Only creates a local commit; push with
#   git push origin rebrand/<tag>
set -euo pipefail

tag="${1:?usage: $0 <tag>}"
repo_root="$(git rev-parse --show-toplevel)"
branch="rebrand/$tag"
java_bin="${JAVA_HOME:+$JAVA_HOME/bin/}java"

snapshot="$(git -C "$repo_root" log upstream/main --format=%H --grep="^Upstream-Tag: $tag$" -n 1)"
if [ -z "$snapshot" ]; then
    echo "No snapshot of $tag on upstream/main; run tools/upstream/import-snapshot.sh $tag first." >&2
    exit 1
fi

work="$(mktemp -d)"
trap 'git -C "$repo_root" worktree remove --force "$work/source" >/dev/null 2>&1 || true;
      git -C "$repo_root" worktree remove --force "$work/target" >/dev/null 2>&1 || true;
      rm -rf "$work"' EXIT

git -C "$repo_root" worktree add --quiet --detach "$work/source" "$snapshot"
if git -C "$repo_root" rev-parse --verify --quiet "refs/heads/$branch" >/dev/null; then
    echo "$branch already exists; delete it first to regenerate." >&2
    exit 1
fi
git -C "$repo_root" worktree add --quiet -b "$branch" "$work/target" "$snapshot"

# Empty the target tree (keeping .git), then write the renamed copy.
git -C "$work/target" rm -r --quiet -- . >/dev/null
find "$work/target" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
"$java_bin" "$repo_root/tools/rebrand/Rebrand.java" \
    --table "$repo_root/tools/rebrand/rename-table.yaml" \
    --report "$work/report.md" \
    "$work/source" "$work/target" | grep -E '^- '

git -C "$work/target" add --all --force
table_sha="$(sha256sum "$repo_root/tools/rebrand/rename-table.yaml" | cut -d' ' -f1)"
tool_sha="$(sha256sum "$repo_root/tools/rebrand/Rebrand.java" | cut -d' ' -f1)"
git -C "$work/target" commit --quiet -F - <<MSG
Rebrand Hazelcast CE $tag

Generated by tools/rebrand/rebrand.sh from the upstream/main snapshot of
$tag. Do not edit by hand; change tools/rebrand/rename-table.yaml and
regenerate instead.

Upstream-Tag: $tag
Upstream-Snapshot: $snapshot
Rename-Table-SHA256: $table_sha
Rebrand-Tool-SHA256: $tool_sha
MSG

echo "Committed $branch: $(git -C "$work/target" rev-parse --short HEAD)"
