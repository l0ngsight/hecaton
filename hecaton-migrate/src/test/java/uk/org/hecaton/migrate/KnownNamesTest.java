package uk.org.hecaton.migrate;

import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Checks that {@code known-names.txt} lists exactly the {@code hecaton.*} names (property
 * keys, file names) found as string literals in the Hecaton main sources, plus the config
 * file names. Run with {@code -Dhecaton.migrate.updateKnownNames=true} to rewrite the file.
 */
class KnownNamesTest {

    static final Path RESOURCE = Path.of("src/main/resources/uk/org/hecaton/migrate/known-names.txt");

    private static final Pattern LITERAL = Pattern.compile("\"(hecaton[.-][A-Za-z0-9_.-]*)\"");
    private static final Pattern CONFIG_FILE =
            Pattern.compile("hecaton(-client(-failover)?)?(-default)?\\.(xml|yaml|yml)");
    /** Not part of the migration: this module and test-only modules. */
    private static final Set<String> EXCLUDED_MODULES =
            Set.of("hecaton-migrate", "hecaton-migrate-rewrite", "hecaton-it", "hecaton-build-utils", "modulepath-tests");
    /** Default config file names that the code builds at runtime rather than spelling out. */
    private static final List<String> CONFIG_FILES = List.of(
            "hecaton.xml", "hecaton.yaml", "hecaton.yml",
            "hecaton-client.xml", "hecaton-client.yaml", "hecaton-client.yml",
            "hecaton-client-failover.xml", "hecaton-client-failover.yaml", "hecaton-client-failover.yml");

    private static final String HEADER = """
            # Names that Hecaton reads (property keys, file names): the string literals starting with
            # "hecaton." in the Hecaton main sources, and the config file names. A name ending in "."
            # is a prefix. The migration tools rename a Hazelcast name only if its Hecaton form is listed.
            # Generated by KnownNamesTest (-Dhecaton.migrate.updateKnownNames=true); do not edit.
            """;

    @Test
    void knownNamesMatchSources() throws IOException {
        String root = System.getProperty("hecaton.source.root", "");
        String expected = generate(Path.of(root.isBlank() ? ".." : root).toAbsolutePath().normalize());
        if (Boolean.getBoolean("hecaton.migrate.updateKnownNames")) {
            Files.writeString(RESOURCE, expected, StandardCharsets.UTF_8);
        }
        assertThat(Files.readString(RESOURCE, StandardCharsets.UTF_8))
                .as("known-names.txt is out of date; run KnownNamesTest with -Dhecaton.migrate.updateKnownNames=true")
                .isEqualTo(expected);
    }

    static String generate(Path sourceRoot) throws IOException {
        Set<String> names = new TreeSet<>(CONFIG_FILES);
        for (Path sources : mainSourceDirectories(sourceRoot)) {
            try (Stream<Path> files = Files.walk(sources)) {
                for (Path file : files.filter(p -> p.toString().endsWith(".java")).toList()) {
                    Matcher m = LITERAL.matcher(Files.readString(file, StandardCharsets.UTF_8));
                    while (m.find()) {
                        String name = m.group(1);
                        if (name.startsWith("hecaton.") ? name.length() > "hecaton.".length()
                                : CONFIG_FILE.matcher(name).matches()) {
                            names.add(name);
                        }
                    }
                }
            }
        }
        StringBuilder sb = new StringBuilder(HEADER);
        names.forEach(n -> sb.append(n).append('\n'));
        return sb.toString();
    }

    private static List<Path> mainSourceDirectories(Path root) throws IOException {
        List<Path> result = new ArrayList<>();
        try (Stream<Path> walk = Files.walk(root, 4)) {
            walk.filter(p -> p.endsWith(Path.of("src", "main", "java")))
                    .filter(p -> !p.toString().contains("/target/") && !p.toString().contains("/src/test/"))
                    .filter(p -> !EXCLUDED_MODULES.contains(root.relativize(p).getName(0).toString()))
                    .sorted()
                    .forEach(result::add);
        }
        return result;
    }
}
